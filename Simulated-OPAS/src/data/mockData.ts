export function calculatePassportFees(booklet: BookletType, speed: ProcessingSpeed): FeeBreakdown {
  const baseFee = 500.0; // Standard 32-page passport: K500 ZMW
  const bookletFee = booklet === 'FREQUENT_48' ? 200.0 : 0.0; // 48-page jumbo: +K200 ZMW

  let speedFee = 0.0;
  if (speed === 'EXPRESS') speedFee = 300.0; // 3-5 days
  if (speed === 'URGENT_24H') speedFee = 600.0; // 24-48 hours

  const biometricProcessingFee = 50.0; // Biometric data capture statutory fee
  const subtotal = baseFee + bookletFee + speedFee + biometricProcessingFee;
  const tax = 0.0; // Government statutory fees exempt from VAT
  const total = subtotal;

  return {
    baseFee,
    bookletFee,
    speedFee,
    biometricProcessingFee,
    tax,
    total,
  };
}

